class TitleScene
  def initialize
    @belts = save_get("belts", {})
    @best_ko = save_get("best_ko", {})
    @sel = 0
    @tick = 0
    music(:intro_bgm, true, 0.65)
  end

  def update
    @tick += 1
    @sel = (@sel - 1 + $champs.size) % $champs.size if btnp(:left) || btnp(:up)
    @sel = (@sel + 1) % $champs.size if btnp(:right) || btnp(:down)

    if btnp(:mouse_l)
      mx = mouse_x
      my = mouse_y
      if my >= 88 && my <= 162
        idx = ((mx - 15) / 59).to_i
        if idx >= 0 && idx < $champs.size
          if @sel == idx
            start_bout
            return
          else
            @sel = idx
            sfx(:select)
          end
        end
      elsif my >= 182 && my <= 210 && mx >= 80 && mx <= 240
        start_bout
        return
      end
    end

    start_bout if btnp(1) || btnp(2)
  end

  def start_bout
    sfx(:bell, -1, 0.85, 1.0)
    run BoutScene.new({ idx: @sel })
  end

  def draw
    cls(0)
    bg(:cyber, dim: 0.48, tint: "#8030A8", scroll_x: @tick * 0.25, mirror_x: true)

    print_text("CYBER PUNCH CHAMPS", 160, 16, 10, 16, 1.0, :center, 0, 2)
    print_text("READ THE SOUND TELLS & LAND COUNTER KOs!", 160, 38, 14, 8, 1.0, :center, 0)

    champ_cnt = @belts.size
    print_text("BELTS WON: #{champ_cnt}/#{$champs.size}", 160, 56, 11, 8, 1.0, :center, 0)

    i = 0
    while i < $champs.size
      ch = $champs[i]
      bx = 15 + i * 59
      by = 88
      sel = (@sel == i)
      won = @belts.has_key?(i.to_s)
      rectfill(bx, by, 54, 72, sel ? 1 : 0, 0.88)
      rect(bx, by, 54, 72, sel ? 10 : ch[:col], sel ? 2 : 1)

      if ch[:pal]
        ch[:pal].each { |k, v| pal(k, v) }
      end
      spr(spr_id(:boxer, (@tick / 15) % 2), bx + 3, by + 4, false, nil, 0.0, 1.0)
      pal

      rk = won ? "KO #{ @best_ko[i.to_s] }s" : "##{5 - i}"
      print_text(rk, bx + 27, by + 56, won ? 10 : 7, 8, 1.0, :center, 0)
      i += 1
    end

    cur = $champs[@sel]
    print_text("#{cur[:rank]}: #{cur[:name]} (HP #{cur[:hp]})", 160, 166, cur[:col], 8, 1.0, :center, 0)

    rectfill(80, 182, 160, 24, 2, 0.92)
    rect(80, 182, 160, 24, 10, 2)
    print_text("STEP INTO RING (Z)", 160, 190, 10, 8, 1.0, :center, 0)

    print_text("L/R: DODGE  DN: GUARD  Z/X: PUNCH (+UP: HEAD)", 160, 222, 6, 8, 1.0, :center, 0)
  end
end

class BoutScene
  def initialize(opts)
    @idx = opts[:idx] || 0
    @spec = $champs[@idx]
    @w = $cfg[:w]
    @h = $cfg[:h]

    @p_hp = $cfg[:player_max_hp]
    @p_stam = $cfg[:player_max_stam]
    @p_dodge = 0      # -1 left, +1 right
    @p_dodge_t = 0
    @p_guard = false
    @p_punch = 0      # 0 none, 1 left, 2 right
    @p_punch_t = 0
    @p_head = false
    @p_stars = 0
    @p_inv = 0

    @e_hp = @spec[:hp]
    @e_max_hp = @spec[:hp]
    @e_state = :idle  # :idle, :tell_l, :tell_r, :tell_u, :strike, :stun, :hurt
    @e_t = 45
    @e_guard_high = false
    @e_knockdowns = 0

    @tick = 0
    @timer = $cfg[:round_sec] * 60
    @shake = 0.0
    @hitstop = 0
    @popups = []
    @particles = []
    @state = :play
    @state_t = 0

    music(:bout_bgm, true, 0.72)
  end

  def update
    if @state != :play
      @state_t += 1
      if @state_t > 35 && (btnp(1) || btnp(2) || btnp(:mouse_l))
        if @state == :win && @idx + 1 < $champs.size
          run BoutScene.new({ idx: @idx + 1 })
        else
          run TitleScene.new
        end
      end
      return
    end

    if @hitstop > 0
      @hitstop -= 1
      return
    end

    @tick += 1
    @timer -= 1 if @timer > 0
    @shake *= 0.82
    @shake = 0.0 if @shake < 0.2
    @p_inv -= 1 if @p_inv > 0

    if @timer <= 0
      sfx(:bell)
      stop_music
      @state = :lose
      @state_t = 0
      return
    end

    update_player
    update_enemy
    update_fx
  end

  def update_player
    @p_guard = btn(:down) && @p_dodge_t <= 0 && @p_punch_t <= 0

    if @p_dodge_t > 0
      @p_dodge_t -= 1
      @p_dodge = 0 if @p_dodge_t <= 0
    elsif @p_punch_t <= 0
      if btnp(:left)
        @p_dodge = -1
        @p_dodge_t = $cfg[:dodge_frames]
        sfx(:dash, -1, 0.45, 1.25)
      elsif btnp(:right)
        @p_dodge = 1
        @p_dodge_t = $cfg[:dodge_frames]
        sfx(:dash, -1, 0.45, 1.25)
      end
    end

    if @p_punch_t > 0
      @p_punch_t -= 1
      if @p_punch_t == ($cfg[:punch_frames] / 2)
        resolve_player_punch
      end
      @p_punch = 0 if @p_punch_t <= 0
    elsif @p_dodge_t <= 0 && !@p_guard && @p_stam >= 12
      if btnp(1)
        start_punch(1)
      elsif btnp(2)
        start_punch(2)
      end
    end

    @p_stam = (@p_stam + (@p_guard ? 0.25 : 0.65)).clamp(0.0, $cfg[:player_max_stam].to_f)
  end

  def start_punch(side)
    @p_punch = side
    @p_punch_t = $cfg[:punch_frames]
    @p_head = btn(:up)
    @p_stam -= 12
    sfx(:slash, -1, 0.45, side == 1 ? 1.15 : 0.95)
  end

  def resolve_player_punch
    # Check if enemy is vulnerable (stunned, or mid-tell for counter!)
    if @e_state == :tell_l || @e_state == :tell_r || @e_state == :tell_u
      # Counter-punch!
      dmg = 18 + (@p_stars > 0 ? 12 : 0)
      @p_stars = (@p_stars - 1).clamp(0, 3) if @p_stars > 0
      @e_hp -= dmg
      @e_state = :stun
      @e_t = 44
      @hitstop = 4
      @shake = 7.0
      sfx(:hit, -1, 0.95, 1.35)
      sfx(:crowd_cheer, -1, 0.6, 1.0)
      add_popup(160, 72, "COUNTER! -#{dmg}", 10)
      spawn_sparks(160, 92, 10, 14)
    elsif @e_state == :stun || !@e_guard_high || !@p_head
      base = (@p_stars >= 3) ? 26 : 10
      if @p_stars >= 3
        @p_stars = 0
        add_popup(160, 68, "STAR UPPER! -#{base}", 14)
        @hitstop = 5
        @shake = 8.0
        sfx(:explode, -1, 0.85, 1.2)
      else
        add_popup(160, 86, "-#{base}", 7)
        @hitstop = 2
        @shake = 3.5
        sfx(:hit, -1, 0.75, 1.0)
      end
      @e_hp -= base
      @e_state = :hurt if @e_state != :stun
      @e_t = 16 if @e_state == :hurt
      spawn_sparks(160, @p_head ? 84 : 112, 7, 8)
    else
      # Blocked by enemy high guard!
      sfx(:click, -1, 0.7, 0.7)
      add_popup(160, 82, "BLOCKED!", 6)
    end

    if @e_hp <= 0
      @e_hp = 0
      ko_enemy
    end
  end

  def ko_enemy
    sfx(:bell, -1, 0.95, 1.0)
    sfx(:crowd_cheer, -1, 0.8, 1.1)
    stop_music
    @shake = 10.0
    @hitstop = 6
    sec = (($cfg[:round_sec] * 60 - @timer) / 60).to_i
    belts = save_get("belts", {})
    belts[@idx.to_s] = true
    save_set("belts", belts)
    bko = save_get("best_ko", {})
    prev = bko[@idx.to_s]
    if prev.nil? || sec < prev.to_i
      bko[@idx.to_s] = sec
      save_set("best_ko", bko)
    end
    @ko_sec = sec
    @state = :win
    @state_t = 0
  end

  def update_enemy
    @e_t -= 1
    if @e_t <= 0
      case @e_state
      when :idle, :hurt, :stun
        # Pick next attack tell with unique synth cue!
        roll = rand(3)
        if roll == 0
          @e_state = :tell_l
          sfx(:telegraph_jab, -1, 0.8, @spec[:sfx_pitch])
        elsif roll == 1
          @e_state = :tell_r
          sfx(:telegraph_hook, -1, 0.85, @spec[:sfx_pitch])
        else
          @e_state = :tell_u
          sfx(:telegraph_upper, -1, 0.9, @spec[:sfx_pitch])
        end
        @e_t = @spec[:tell_f]
      when :tell_l, :tell_r, :tell_u
        execute_enemy_strike(@e_state)
        @e_state = :strike
        @e_t = 14
      when :strike
        @e_state = :idle
        @e_t = (32 / @spec[:spd]).to_i + rand(20)
        @e_guard_high = (rand(2) == 0)
      end
    end
  end

  def execute_enemy_strike(tell_kind)
    dodged = false
    if tell_kind == :tell_l && @p_dodge == 1
      dodged = true
    elsif tell_kind == :tell_r && @p_dodge == -1
      dodged = true
    elsif tell_kind == :tell_u && @p_dodge != 0
      dodged = true
    end

    if dodged
      @p_stars = (@p_stars + 1).clamp(0, 3)
      sfx(:coin, -1, 0.75, 1.0 + @p_stars * 0.18)
      add_popup(160, 146, "DODGE! +STAR", 11)
      return
    end

    return if @p_inv > 0
    dmg = @spec[:dmg]
    if @p_guard && tell_kind != :tell_u
      dmg = (dmg * 0.25).to_i
      sfx(:click, -1, 0.7, 0.8)
      add_popup(160, 165, "GUARD -#{dmg}", 12)
    else
      @p_inv = 20
      @shake = 6.5
      @hitstop = 3
      sfx(:hit, -1, 0.95, 0.65)
      add_popup(160, 165, "HIT! -#{dmg}", 8)
    end
    @p_hp = (@p_hp - dmg).clamp(0, $cfg[:player_max_hp])
    if @p_hp <= 0
      sfx(:bell, -1, 0.9, 0.8)
      sfx(:gameover)
      stop_music
      @state = :lose
      @state_t = 0
    end
  end

  def add_popup(x, y, txt, col)
    @popups << { x: x, y: y, txt: txt, col: col, t: 36 }
  end

  def spawn_sparks(x, y, col, n)
    i = 0
    while i < n
      a = rand * Math::PI * 2.0
      sp = 1.0 + rand * 3.0
      @particles << { x: x.to_f, y: y.to_f, vx: cos(a) * sp, vy: sin(a) * sp, col: col, t: 14 + rand(10) }
      i += 1
    end
  end

  def update_fx
    i = @particles.size - 1
    while i >= 0
      pt = @particles[i]
      pt[:x] += pt[:vx]
      pt[:y] += pt[:vy]
      pt[:t] -= 1
      @particles.delete_at(i) if pt[:t] <= 0
      i -= 1
    end

    i = @popups.size - 1
    while i >= 0
      @popups[i][:y] -= 0.45
      @popups[i][:t] -= 1
      @popups.delete_at(i) if @popups[i][:t] <= 0
      i -= 1
    end
  end

  def draw
    cls(0)
    bg(@spec[:bg], dim: 0.48, tint: @spec[:tint])

    sx = @shake > 0 ? (rand * @shake * 2.0 - @shake) : 0.0
    sy = @shake > 0 ? (rand * @shake * 2.0 - @shake) : 0.0
    camera(sx, sy)

    draw_ring
    draw_enemy_boxer
    draw_player_gloves
    draw_fx

    camera
    blend(:normal)
    draw_hud
    draw_overlay if @state != :play
  end

  def draw_ring
    # 3D perspective ring mat & ropes
    quadfill(32, 128, 288, 128, 320, 240, 0, 240, 1, 0.85)
    line(24, 112, 296, 112, 12, 2, 0.75)
    line(16, 122, 304, 122, 14, 2, 0.75)
    line(8, 132, 312, 132, 8, 2, 0.75)
    rect(40, 128, 240, 100, 12, 1, 0.3)
  end

  def draw_enemy_boxer
    ex = 136
    ey = 68
    frame = 0
    flip = false

    if @e_state == :tell_l
      frame = 2
      ex -= 10
    elsif @e_state == :tell_r
      frame = 2
      flip = true
      ex += 10
    elsif @e_state == :tell_u
      frame = 3
      ey += 8
    elsif @e_state == :strike
      frame = 4
      ey += 10
    elsif @e_state == :stun || @e_state == :hurt
      frame = 5
      ex += (sin(@tick * 0.9) * 3).to_i
    else
      frame = (@tick / 15) % 2
      ey += (sin(@tick * 0.12) * 2).to_i
    end

    if @spec[:pal]
      @spec[:pal].each { |k, v| pal(k, v) }
    end
    spr(spr_id(:boxer, frame), ex, ey, flip, nil, 0.0, 1.8)
    pal

    # Tell flash aura
    if @e_state == :tell_l || @e_state == :tell_r || @e_state == :tell_u
      blend(:add)
      tx = @e_state == :tell_l ? 132 : (@e_state == :tell_r ? 188 : 160)
      circfill(tx, 96, 12 + (@tick % 4) * 2, 10, 0.45)
      blend(:normal)
    end
  end

  def draw_player_gloves
    px = 160 + @p_dodge * 34
    py = 186 + (@p_guard ? -16 : 0)

    # Translucent neon boxer silhouette
    rectfill(px - 18, py + 8, 36, 46, 12, 0.28)
    circfill(px, py - 4, 12, 12, 0.28)

    # Left & Right gloves
    lx = px - 26
    ly = py + 8
    rx = px + 26
    ry = py + 8

    if @p_punch == 1
      ly -= (@p_head ? 74 : 52)
      lx += 18
    elsif @p_punch == 2
      ry -= (@p_head ? 74 : 52)
      rx -= 18
    end

    circfill(lx, ly, 11, 8, 0.9)
    circ(lx, ly, 11, 7, 1.0)
    circfill(rx, ry, 11, 8, 0.9)
    circ(rx, ry, 11, 7, 1.0)
  end

  def draw_fx
    blend(:add)
    i = 0
    while i < @particles.size
      pt = @particles[i]
      circfill(pt[:x], pt[:y], 2, pt[:col], 0.85)
      i += 1
    end
    blend(:normal)

    i = 0
    while i < @popups.size
      p = @popups[i]
      print_text(p[:txt], p[:x], p[:y], p[:col], 8, 1.0, :center, 0)
      i += 1
    end
  end

  def draw_hud
    rectfill(0, 0, @w, 26, 0, 0.85)

    # Player HP (Left)
    print_text("YOU", 8, 4, 12, 8, 1.0, :left, 0)
    rectfill(8, 14, 100, 7, 1)
    pw = ((@p_hp.to_f / $cfg[:player_max_hp]) * 100).to_i.clamp(0, 100)
    rectfill(8, 14, pw, 7, 11)
    rect(8, 14, 100, 7, 7, 1)

    # Timer & Stars (Center)
    sec = (@timer / 60).to_i
    print_text(sprintf("%02d", sec), 160, 4, 10, 8, 1.0, :center, 0)
    st_str = ""
    s = 0
    while s < 3
      st_str += (s < @p_stars ? "★" : "☆")
      s += 1
    end
    print_text(st_str, 160, 15, 10, 8, 1.0, :center, 0)

    # Enemy HP (Right)
    print_text(@spec[:name], 312, 4, @spec[:col], 8, 1.0, :right, 0)
    rectfill(212, 14, 100, 7, 1)
    ew = ((@e_hp.to_f / @e_max_hp) * 100).to_i.clamp(0, 100)
    rectfill(212, 14, ew, 7, 8)
    rect(212, 14, 100, 7, 7, 1)

    # Stamina bar bottom left
    rectfill(8, 226, 80, 6, 0, 0.8)
    sw = ((@p_stam / $cfg[:player_max_stam].to_f) * 80).to_i.clamp(0, 80)
    rectfill(8, 226, sw, 6, 12)
    rect(8, 226, 80, 6, 7, 1)
  end

  def draw_overlay
    rectfill(44, 62, 232, 108, 0, 0.92)
    b_col = (@state == :win) ? 10 : 8
    rect(44, 62, 232, 108, b_col, 2)
    title = (@state == :win) ? "KNOCKOUT VICTORY!" : "DOWN FOR THE COUNT..."
    print_text(title, 160, 78, b_col, 16, 1.0, :center, 0)
    if @state == :win
      print_text("KO TIME: #{@ko_sec}s", 160, 112, 10, 8, 1.0, :center, 0)
    end
    print_text("PRESS Z OR X TO CONTINUE", 160, 142, 11, 8, 1.0, :center, 0)
  end
end

